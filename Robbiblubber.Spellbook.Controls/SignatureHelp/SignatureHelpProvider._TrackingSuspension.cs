namespace Robbiblubber.Spellbook.Controls;



partial class SignatureHelpProvider
{
	//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	// [class] _TrackingSuspension                                                                                      //
	//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

	/// <summary>This class represents a suspension of the tracking of a control, created by <see cref="SuspendTracking"/>.</summary>
	/// <remarks>Disposing the instance resumes tracking. Disposing it more than once has no further effect.</remarks>
	private sealed class _TrackingSuspension: IDisposable
	{
		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		// private members                                                                                              //
		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		/// <summary>Binding, NULL after disposal.</summary>
		private _Binding? _Target;



		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		// constructors                                                                                                 //
		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		/// <summary>Creates a new instance of this class.</summary>
		/// <param name="binding">Binding.</param>
		public _TrackingSuspension(_Binding binding)
		{
			_Target = binding;
		}



		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		// [interface] IDisposable                                                                                      //
		//////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		/// <inheritdoc/>
		public void Dispose()
		{
			_Target?.ResumeTracking();
			_Target = null;
		}
	}
}
